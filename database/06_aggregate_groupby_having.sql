-- =============================================================================
-- Eco-Track – Carbon Footprint Analyzer
-- Script: 06_aggregate_groupby_having.sql
-- Purpose: Aggregate functions, GROUP BY, HAVING, and advanced aggregation
--          against the EcoTrack schema and sample data.
-- Prerequisite: 01_create_database.sql, 02_create_tables.sql, 03_insert_data.sql
--
-- Emission grain:
--   All kg CO2e totals come from CARBON_RECORD.carbon_footprint.
--   Activity tables (TRANSPORTATION, FOOD_CONSUMPTION, ELECTRICITY_USAGE) are
--   1:1 details of a record and are not joined when summing emissions, so a
--   record cannot be counted more than once.
--
-- City:
--   There is no city column. City is the middle part of USERS.address
--   (Locality, City, State), extracted the same way as 04_basic_queries.sql.
--
-- Thresholds in SECTION 3 are session variables so they can be changed
-- without editing the SELECT statements.
-- =============================================================================

USE EcoTrack;

-- Named thresholds used by the HAVING queries below.
SET @user_total_emission_threshold   = 100;  -- kg CO2e per user
SET @category_total_emission_threshold = 100;  -- kg CO2e per category
SET @min_records_per_user            = 3;    -- carbon records per user

-- =============================================================================
-- SECTION 1 – AGGREGATE FUNCTIONS
-- =============================================================================

-- 1. Total carbon emissions across every carbon record (kg CO2e).
--    SUM ignores NULL carbon_footprint values; COALESCE returns 0 if the table
--    is empty.
SELECT
    COALESCE(SUM(carbon_footprint), 0) AS total_emissions_kg_co2e
FROM CARBON_RECORD;

-- 2. Average carbon emissions per carbon record (kg CO2e).
--    AVG ignores NULL values and does not treat missing rows as zero.
SELECT
    AVG(carbon_footprint) AS average_emissions_kg_co2e
FROM CARBON_RECORD;

-- 3. Highest and lowest carbon_footprint among all carbon records.
SELECT
    MAX(carbon_footprint) AS maximum_emissions_kg_co2e,
    MIN(carbon_footprint) AS minimum_emissions_kg_co2e
FROM CARBON_RECORD;

-- 4. Number of registered users (one row in USERS = one registered account).
SELECT
    COUNT(*) AS total_registered_users
FROM USERS;

-- 5. Number of carbon records logged in CARBON_RECORD.
SELECT
    COUNT(*) AS total_carbon_records
FROM CARBON_RECORD;

-- =============================================================================
-- SECTION 2 – GROUP BY
-- =============================================================================

-- 1. Total carbon emissions for each user.
--    LEFT JOIN keeps users who have not logged any records (SUM then becomes
--    NULL; COALESCE turns that into 0). GROUP BY user_id is enough in MySQL 8
--    because user_id is the primary key of USERS; name and email are included
--    for a stable result set.
SELECT
    u.user_id                          AS user_number,
    u.name                             AS user_name,
    u.email                            AS email_address,
    COALESCE(SUM(cr.carbon_footprint), 0) AS total_emissions_kg_co2e
FROM USERS AS u
LEFT JOIN CARBON_RECORD AS cr
       ON u.user_id = cr.user_id
GROUP BY u.user_id, u.name, u.email
ORDER BY total_emissions_kg_co2e DESC, u.name ASC;

-- 2. Average emissions per carbon record for each category.
--    LEFT JOIN keeps categories that have no logs yet (AVG is NULL for those).
SELECT
    cat.category_id          AS category_number,
    cat.category_name        AS activity_category,
    AVG(cr.carbon_footprint) AS average_emissions_kg_co2e,
    COUNT(cr.record_id)      AS carbon_record_count
FROM CATEGORY AS cat
LEFT JOIN CARBON_RECORD AS cr
       ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
ORDER BY average_emissions_kg_co2e DESC;

-- 3. Number of carbon records logged by each user.
--    COUNT(cr.record_id) counts only matched records, so users with no logs
--    appear with 0 rather than 1 (which COUNT(*) would produce after a LEFT JOIN).
SELECT
    u.user_id           AS user_number,
    u.name              AS user_name,
    COUNT(cr.record_id) AS carbon_record_count
FROM USERS AS u
LEFT JOIN CARBON_RECORD AS cr
       ON u.user_id = cr.user_id
GROUP BY u.user_id, u.name
ORDER BY carbon_record_count DESC, u.name ASC;

-- 4. Total emissions for each activity category.
SELECT
    cat.category_id                   AS category_number,
    cat.category_name                 AS activity_category,
    COALESCE(SUM(cr.carbon_footprint), 0) AS total_emissions_kg_co2e
FROM CATEGORY AS cat
LEFT JOIN CARBON_RECORD AS cr
       ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
ORDER BY total_emissions_kg_co2e DESC;

-- 5. Total carbon emissions generated by each city.
--    City is parsed from USERS.address. Users with a NULL address are grouped
--    under 'Unknown'. Each carbon record belongs to one user, so joining USERS
--    to CARBON_RECORD does not duplicate emissions.
SELECT
    COALESCE(
        TRIM(SUBSTRING_INDEX(SUBSTRING_INDEX(u.address, ',', 2), ',', -1)),
        'Unknown'
    ) AS city,
    COALESCE(SUM(cr.carbon_footprint), 0) AS total_emissions_kg_co2e,
    COUNT(cr.record_id)                   AS carbon_record_count
FROM USERS AS u
LEFT JOIN CARBON_RECORD AS cr
       ON u.user_id = cr.user_id
GROUP BY city
ORDER BY total_emissions_kg_co2e DESC, city ASC;

-- =============================================================================
-- SECTION 3 – HAVING
-- =============================================================================

-- 1. Users whose total carbon emissions exceed @user_total_emission_threshold.
--    HAVING filters groups after aggregation; WHERE cannot use SUM().
SELECT
    u.user_id                AS user_number,
    u.name                   AS user_name,
    u.email                  AS email_address,
    SUM(cr.carbon_footprint) AS total_emissions_kg_co2e
FROM USERS AS u
INNER JOIN CARBON_RECORD AS cr
        ON u.user_id = cr.user_id
GROUP BY u.user_id, u.name, u.email
HAVING SUM(cr.carbon_footprint) > @user_total_emission_threshold
ORDER BY total_emissions_kg_co2e DESC;

-- 2. Categories whose total emissions exceed @category_total_emission_threshold.
SELECT
    cat.category_id          AS category_number,
    cat.category_name        AS activity_category,
    SUM(cr.carbon_footprint) AS total_emissions_kg_co2e
FROM CATEGORY AS cat
INNER JOIN CARBON_RECORD AS cr
        ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
HAVING SUM(cr.carbon_footprint) > @category_total_emission_threshold
ORDER BY total_emissions_kg_co2e DESC;

-- 3. Users who have logged more than @min_records_per_user carbon records.
SELECT
    u.user_id           AS user_number,
    u.name              AS user_name,
    COUNT(cr.record_id) AS carbon_record_count
FROM USERS AS u
INNER JOIN CARBON_RECORD AS cr
        ON u.user_id = cr.user_id
GROUP BY u.user_id, u.name
HAVING COUNT(cr.record_id) > @min_records_per_user
ORDER BY carbon_record_count DESC, u.name ASC;

-- 4. Categories whose average record emissions exceed the overall average
--    carbon_footprint (computed once across all carbon records).
SELECT
    cat.category_id          AS category_number,
    cat.category_name        AS activity_category,
    AVG(cr.carbon_footprint) AS average_emissions_kg_co2e,
    COUNT(cr.record_id)      AS carbon_record_count
FROM CATEGORY AS cat
INNER JOIN CARBON_RECORD AS cr
        ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
HAVING AVG(cr.carbon_footprint) > (
    SELECT AVG(carbon_footprint)
    FROM CARBON_RECORD
)
ORDER BY average_emissions_kg_co2e DESC;

-- =============================================================================
-- SECTION 4 – ADVANCED AGGREGATION
-- =============================================================================

-- 1. Rank users by total carbon footprint (highest first) using ORDER BY.
--    footprint_rank is 1 for the largest total; ties share the same rank
--    (users with a strictly larger total are counted, then 1 is added).
SELECT
    ranked.user_number,
    ranked.user_name,
    ranked.total_emissions_kg_co2e,
    (
        SELECT COUNT(*)
        FROM (
            SELECT
                user_id,
                SUM(carbon_footprint) AS user_total
            FROM CARBON_RECORD
            GROUP BY user_id
        ) AS other_users
        WHERE other_users.user_total > ranked.total_emissions_kg_co2e
    ) + 1 AS footprint_rank
FROM (
    SELECT
        u.user_id                          AS user_number,
        u.name                             AS user_name,
        COALESCE(SUM(cr.carbon_footprint), 0) AS total_emissions_kg_co2e
    FROM USERS AS u
    LEFT JOIN CARBON_RECORD AS cr
           ON u.user_id = cr.user_id
    GROUP BY u.user_id, u.name
) AS ranked
ORDER BY ranked.total_emissions_kg_co2e DESC, ranked.user_name ASC;

-- 2. Category that contributes the most to total emissions.
--    HAVING equals the maximum category SUM so a tie would return every
--    category that shares the top total.
SELECT
    cat.category_id          AS category_number,
    cat.category_name        AS activity_category,
    SUM(cr.carbon_footprint) AS total_emissions_kg_co2e
FROM CATEGORY AS cat
INNER JOIN CARBON_RECORD AS cr
        ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
HAVING SUM(cr.carbon_footprint) = (
    SELECT MAX(category_total.total_emissions)
    FROM (
        SELECT SUM(carbon_footprint) AS total_emissions
        FROM CARBON_RECORD
        GROUP BY category_id
    ) AS category_total
);

-- 3. Percentage contribution of each category to overall emissions.
--    NULLIF protects against division by zero if CARBON_RECORD is empty.
--    Percentages are rounded to two decimal places.
SELECT
    cat.category_id                   AS category_number,
    cat.category_name                 AS activity_category,
    COALESCE(SUM(cr.carbon_footprint), 0) AS total_emissions_kg_co2e,
    ROUND(
        COALESCE(SUM(cr.carbon_footprint), 0) * 100
        / NULLIF(
            (SELECT SUM(carbon_footprint) FROM CARBON_RECORD),
            0
          ),
        2
    ) AS percentage_of_total_emissions
FROM CATEGORY AS cat
LEFT JOIN CARBON_RECORD AS cr
       ON cat.category_id = cr.category_id
GROUP BY cat.category_id, cat.category_name
ORDER BY percentage_of_total_emissions DESC;

-- 4. Users with the highest average emissions per activity (per carbon record).
--    "Activity" here is one CARBON_RECORD. Users whose AVG matches the maximum
--    user-level average are returned (ties included).
SELECT
    u.user_id                AS user_number,
    u.name                   AS user_name,
    AVG(cr.carbon_footprint) AS average_emissions_per_activity_kg_co2e,
    COUNT(cr.record_id)      AS carbon_record_count
FROM USERS AS u
INNER JOIN CARBON_RECORD AS cr
        ON u.user_id = cr.user_id
GROUP BY u.user_id, u.name
HAVING AVG(cr.carbon_footprint) = (
    SELECT MAX(user_avg.average_emissions)
    FROM (
        SELECT AVG(carbon_footprint) AS average_emissions
        FROM CARBON_RECORD
        GROUP BY user_id
    ) AS user_avg
);
